import type { MetadataRoute } from "next";

/** Search and AI assistant crawlers we explicitly welcome, so answers can cite the site. */
export const AI_CRAWLERS = [
  "GPTBot",
  "OAI-SearchBot",
  "ChatGPT-User",
  "ClaudeBot",
  "Claude-SearchBot",
  "Claude-User",
  "PerplexityBot",
  "Perplexity-User",
  "Google-Extended",
  "Applebot-Extended",
  "Bingbot",
];

const PRIVATE = ["/admin", "/admin/"];

export function robotsConfig(baseUrl: string): MetadataRoute.Robots {
  return {
    rules: [
      { userAgent: "*", allow: "/", disallow: PRIVATE },
      { userAgent: AI_CRAWLERS, allow: "/", disallow: PRIVATE },
    ],
    sitemap: `${baseUrl}/sitemap.xml`,
  };
}
